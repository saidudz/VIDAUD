/**
 * Title / item-id validation shared by the queue, playlist, downloader, history
 * and completed managers.
 *
 * An item is only ever shown or queued when it carries a REAL title (never a
 * placeholder like "Untitled", "Unknown", "Item 21" or an empty string), a
 * valid URL and a stable id. Everything else is excluded BEFORE a download job
 * is created — no fake fallback title is ever substituted.
 */

/** Strips a leading playlist index ("21 - Untitled" -> "Untitled"). */
export function stripPlaylistIndexPrefix(title: string): string {
  return (title || '').trim().replace(/^\d+\s*[-–—.\s]\s*/, '').trim()
}

/**
 * True when the title carries no real metadata: empty, a placeholder
 * ("Untitled", "Unknown"), or a numbered placeholder ("21 - Untitled").
 */
export function isInvalidTitle(title: unknown): boolean {
  const raw = typeof title === 'string' ? title.trim() : ''
  if (!raw) return true
  const t = stripPlaylistIndexPrefix(raw).toLowerCase()
  return t.length === 0 || t === 'untitled' || t === 'unknown' || /^item\s*\d+$/.test(t)
}

/** True when the title is a real, usable name (the inverse of isInvalidTitle). */
export function hasRealTitle(title: unknown): boolean {
  return !isInvalidTitle(title)
}

/**
 * True when a file name carries a real title. The extension is stripped first
 * so "21 - Untitled.mp3" is rejected while "Song Name.mp3" is kept.
 */
export function hasRealFileName(fileName: unknown): boolean {
  if (typeof fileName !== 'string') return false
  const base = fileName.trim().replace(/\.[^/.]+$/, '')
  return hasRealTitle(base)
}

/** True when an item id is missing or a placeholder generated by the UI. */
export function isPlaceholderItemId(id: unknown): boolean {
  if (typeof id !== 'string') return true
  const t = id.trim()
  return t.length === 0 || /^item-\d+$/.test(t)
}
